export type MessageKey = keyof typeof translations.vi;

export function getLang(c: Context): "vi" | "en" {
  const header = c.req.header("Accept-Language") || "vi";
  return header.startsWith("en") ? "en" : "vi";
}

export function t(c: Context, key: MessageKey, params?: Record<string, string>): string {
  const lang = getLang(c);
  let msg = translations[lang][key] || translations["vi"][key] || String(key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      msg = msg.replaceAll(`{${k}}`, v);
    }
  }
  return msg;
}
